import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const app = resolve(import.meta.dirname, '..');
const source = resolve(app, '../docs/schemas/api-v1');
const target = resolve(app, 'src/generated/schemas');
await mkdir(target, { recursive: true });
const names = ['command.schema.json','event.schema.json','export.schema.json','session-provision.schema.json','status.schema.json'];
for (const name of names) await cp(resolve(source, name), resolve(target, name));
const digest = createHash('sha256');
for (const name of names) digest.update(await readFile(resolve(source, name)));
await writeFile(resolve(app, 'src/generated/contract-meta.ts'), `// Generated by npm run generate. Do not edit.\nexport const CONTRACT_SHA256 = '${digest.digest('hex')}';\n`);
